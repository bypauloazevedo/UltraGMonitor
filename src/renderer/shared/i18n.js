  const STRINGS = { en, es };
  let lang = 'pt';
  let staticNodes = null;

  function pick(locale) {
    const l = String(locale || '').toLowerCase();
    if (l.startsWith('pt')) return 'pt';
    if (l.startsWith('es')) return 'es';
    return 'en';
  }

  function setLang(next) {
    lang = LANGS.includes(next) ? next : 'pt';
    if (typeof document !== 'undefined') document.documentElement.lang = LOCALES[lang];
    return lang;
  }

  function t(text, vars) {
    let out = (lang !== 'pt' && STRINGS[lang][text]) || text;
    if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return out;
  }

  function collect(scope) {
    const list = [];
    const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const parent = node.parentElement;
      if (!parent || parent.closest('script, style, svg, [data-no-i18n]')) continue;
      const key = node.nodeValue.replace(/\s+/g, ' ').trim();
      if (!key) continue;
      const [lead] = node.nodeValue.match(/^\s*/);
      const [trail] = node.nodeValue.match(/\s*$/);
      list.push({ node, key, lead, trail });
    }
    for (const el of scope.querySelectorAll('[placeholder], [title]')) {
      for (const attr of ['placeholder', 'title']) {
        if (el.hasAttribute(attr)) list.push({ el, attr, key: el.getAttribute(attr) });
      }
    }
    return list;
  }

  function apply(scope) {
    if (typeof document === 'undefined') return;
    if (!staticNodes) staticNodes = { title: document.title, list: collect(scope || document.body) };
    document.title = t(staticNodes.title);
    for (const item of staticNodes.list) {
      if (item.node) item.node.nodeValue = `${item.lead}${t(item.key)}${item.trail}`;
      else item.el.setAttribute(item.attr, t(item.key));
    }
  }

  return {
    LANGS,
    pick,
    setLang,
    t,
    apply,
    lang: () => lang,
    locale: () => LOCALES[lang],
  };
